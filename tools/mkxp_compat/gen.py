#!/usr/bin/env python3
"""Regenerates NexPlay/MKXP/MkxpCompat.swift from compat.rb. Run `ruby test.rb` first, then this."""
import os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'compat.rb')).read()
trace = open(os.path.join(here, 'trace.rb')).read()
assert '"""' not in src and '"""' not in trace
swift = '''// GENERATED by tools/mkxp_compat/gen.py from tools/mkxp_compat/compat.rb: edit that file, run `ruby test.rb`, then gen.py.
// Ruby stand-ins that NexPlay hands to the mkxp core as a preload script (mkxp.json "preloadScript").
// 8.13.9: DL.malloc / DL::CPtr / DL.dlopen / DL::Importer / Fiddle for games that talk to Windows (LonaRPG's keyboard script).

#if NEXPLAY_MKXP
import Foundation

enum MkxpCompat {
    static let source = #"""
''' + src + '''"""#

    /// 8.13.12: the call-depth trace, only for a game that ended with a stack error (see MkxpRunner.coreMessage).
    static let traceSource = #"""
''' + trace + '''"""#

    /// UserDefaults key: the next run of this game turns the trace on.
    static func traceKey(_ id: UUID) -> String { "mkxpDeepTrace.\\(id.uuidString)" }

    /// Writes the scripts and returns their paths for mkxp.json's "preloadScript".
    static func installedPaths(for gameID: UUID) -> [String] {
        var files = [("mkxp-compat.rb", source)]
        if UserDefaults.standard.bool(forKey: traceKey(gameID)) { files.append(("mkxp-trace.rb", traceSource)) }
        var paths: [String] = []
        for (name, text) in files {
            let url = Paths.support.appendingPathComponent(name)
            do {
                try FileManager.default.createDirectory(at: Paths.support, withIntermediateDirectories: true)
                if (try? String(contentsOf: url, encoding: .utf8)) != text {
                    try text.write(to: url, atomically: true, encoding: .utf8)
                }
                paths.append(url.path)
            } catch {
                AppLog.log("mkxp compat: could not write \\(name) (\\(error.localizedDescription))")
            }
        }
        return paths
    }
}
#endif
'''
open(os.path.join(here, '..', '..', 'NexPlay', 'MKXP', 'MkxpCompat.swift'), 'w').write(swift)
print('written')
