// MARK: - Plugin manager

struct PluginEntry: Identifiable, Hashable {
    let name: String
    let description: String
    let originalStatus: Bool
    var id: String { name }
}

/// Reads js/plugins.js and keeps on/off overrides in PluginOverrides/<game-uuid>.json.
/// NexSchemeHandler serves a generated js/plugins.js when overrides exist; the game's file is never changed.
enum PluginManager {
    static let folder: URL = {
        let dir = Paths.support.appendingPathComponent("PluginOverrides", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()

    static func pluginsFile(for game: Game) -> URL {
        Paths.entryDirectory(for: game).appendingPathComponent("js/plugins.js")
    }

    private static func overridesURL(_ game: Game) -> URL {
        folder.appendingPathComponent("\(game.id.uuidString).json")
    }

    /// The raw plugin objects from js/plugins.js.
    static func rawPlugins(for game: Game) -> [[String: Any]]? {
        guard let data = try? Data(contentsOf: pluginsFile(for: game)) else { return nil }
        let text = String(decoding: data, as: UTF8.self)
        guard let start = text.firstIndex(of: "["), let end = text.lastIndex(of: "]"), start < end else { return nil }
        let json = String(text[start...end])
        return (try? JSONSerialization.jsonObject(with: Data(json.utf8))) as? [[String: Any]]
    }

    static func plugins(for game: Game) -> [PluginEntry] {
        (rawPlugins(for: game) ?? []).compactMap { object in
            guard let name = object["name"] as? String else { return nil }
            return PluginEntry(name: name, description: object["description"] as? String ?? "",
                               originalStatus: object["status"] as? Bool ?? false)
        }
    }

    static func overrides(for game: Game) -> [String: Bool] {
        guard let data = try? Data(contentsOf: overridesURL(game)),
              let map = try? JSONDecoder().decode([String: Bool].self, from: data) else { return [:] }
        return map
    }

    static func setOverrides(_ map: [String: Bool], for game: Game) {
        if map.isEmpty {
            try? FileManager.default.removeItem(at: overridesURL(game))
        } else if let data = try? JSONEncoder().encode(map) {
            try? data.write(to: overridesURL(game), options: .atomic)
        }
    }

    /// A js/plugins.js with the overrides applied, or nil when there are none.
    static func generatedPluginsJS(for game: Game) -> Data? {
        let map = overrides(for: game)
        guard !map.isEmpty, var list = rawPlugins(for: game) else { return nil }
        for index in list.indices {
            if let name = list[index]["name"] as? String, let status = map[name] {
                list[index]["status"] = status
            }
        }
        guard let json = try? JSONSerialization.data(withJSONObject: list, options: [.prettyPrinted]) else { return nil }
        var out = Data("// Generated by NexPlay from js/plugins.js with plugin overrides.\nvar $plugins =\n".utf8)
        out.append(json)
        out.append(Data(";\n".utf8))
        return out
    }

    /// The scheme handler's override for this game's js/plugins.js.
    static func fileOverride(for game: Game) -> ((String) -> Data?)? {
        guard game.engine.isRPGMaker else { return nil }
        let folder = (game.entry as NSString).deletingLastPathComponent
        let target = (folder.isEmpty ? "js/plugins.js" : folder + "/js/plugins.js").lowercased()
        return { path in
            guard path == target else { return nil }
            return PluginManager.generatedPluginsJS(for: game)
        }
    }
}

struct PluginListView: View {
    @Environment(\.dismiss) private var dismiss
    let game: Game
    var onChange: () -> Void = {}

    @State private var plugins: [PluginEntry] = []
    @State private var overrides: [String: Bool] = [:]

    var body: some View {
        NavigationStack {
            List {
                Section {
                    ForEach(plugins) { plugin in
                        Toggle(isOn: Binding(
                            get: { overrides[plugin.name] ?? plugin.originalStatus },
                            set: { value in
                                if value == plugin.originalStatus {
                                    overrides[plugin.name] = nil
                                } else {
                                    overrides[plugin.name] = value
                                }
                                PluginManager.setOverrides(overrides, for: game)
                                onChange()
                            }
                        )) {
                            VStack(alignment: .leading, spacing: 2) {
                                HStack {
                                    Text(plugin.name).font(.body)
                                    if overrides[plugin.name] != nil {
                                        Text("Changed").font(.caption2).foregroundStyle(.orange)
                                    }
                                }
                                if !plugin.description.isEmpty {
                                    Text(plugin.description).font(.caption).foregroundStyle(.secondary).lineLimit(2)
                                }
                            }
                        }
                    }
                } footer: {
                    Text(plugins.isEmpty
                         ? "No js/plugins.js found."
                         : "Turning plugins off can break a game. Changes apply when the game restarts. The game's own file is not changed.")
                }
                if !overrides.isEmpty {
                    Section {
                        Button("Reset All Plugins", role: .destructive) {
                            overrides = [:]
                            PluginManager.setOverrides([:], for: game)
                            onChange()
                        }
                    }
                }
            }
            .navigationTitle("Plugins")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .navigationBarTrailing) { Button("Done") { dismiss() } }
            }
            .onAppear {
                plugins = PluginManager.plugins(for: game)
                overrides = PluginManager.overrides(for: game)
            }
        }
    }
}

final class PluginsFeature: PlayerFeature {
    private var changed = false

    override func menuItems(for game: Game) -> [UIMenuElement] {
        guard game.engine.isRPGMaker else { return [] }
        return [UIAction(title: "Plugins…", image: UIImage(systemName: "puzzlepiece.extension")) { [weak self] _ in
            self?.showPlugins()
        }]
    }

    private func showPlugins() {
        let game = context.game()
        let view = PluginListView(game: game, onChange: { [weak self] in self?.changed = true })
        let host = UIHostingController(rootView: view)
        context.present(host)
    }

    override func didFinishLoad() {
        changed = false
    }
}

