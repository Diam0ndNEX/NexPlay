import UIKit
import SwiftUI
import WebKit

// Plugin manager (toggle MV/MZ plugins without editing the game's js/plugins.js) and the cheat menu are ideas from
// RPGPlayer, JoiPlay and Empo; the code here is NexPlay's own.

// MARK: - Plugin manager

struct PluginEntry: Identifiable, Hashable {
    let name: String
    let description: String
    let originalStatus: Bool
    var id: String { name }
}

/// Reads js/plugins.js and keeps on/off overrides in PluginOverrides/<game-uuid>.json.
/// NexSchemeHandler serves a generated js/plugins.js when overrides exist; the game's file is never changed.
enum PluginManager {
    static let folder: URL = {
        let dir = Paths.support.appendingPathComponent("PluginOverrides", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()

    static func pluginsFile(for game: Game) -> URL {
        Paths.entryDirectory(for: game).appendingPathComponent("js/plugins.js")
    }

    private static func overridesURL(_ game: Game) -> URL {
        folder.appendingPathComponent("\(game.id.uuidString).json")
    }

    /// The raw plugin objects from js/plugins.js.
    static func rawPlugins(for game: Game) -> [[String: Any]]? {
        guard let data = try? Data(contentsOf: pluginsFile(for: game)) else { return nil }
        let text = String(decoding: data, as: UTF8.self)
        guard let start = text.firstIndex(of: "["), let end = text.lastIndex(of: "]"), start < end else { return nil }
        let json = String(text[start...end])
        return (try? JSONSerialization.jsonObject(with: Data(json.utf8))) as? [[String: Any]]
    }

    static func plugins(for game: Game) -> [PluginEntry] {
        (rawPlugins(for: game) ?? []).compactMap { object in
            guard let name = object["name"] as? String else { return nil }
            return PluginEntry(name: name, description: object["description"] as? String ?? "",
                               originalStatus: object["status"] as? Bool ?? false)
        }
    }

    static func overrides(for game: Game) -> [String: Bool] {
        guard let data = try? Data(contentsOf: overridesURL(game)),
              let map = try? JSONDecoder().decode([String: Bool].self, from: data) else { return [:] }
        return map
    }

    static func setOverrides(_ map: [String: Bool], for game: Game) {
        if map.isEmpty {
            try? FileManager.default.removeItem(at: overridesURL(game))
        } else if let data = try? JSONEncoder().encode(map) {
            try? data.write(to: overridesURL(game), options: .atomic)
        }
    }

    /// A js/plugins.js with the overrides applied, or nil when there are none.
    static func generatedPluginsJS(for game: Game) -> Data? {
        let map = overrides(for: game)
        guard !map.isEmpty, var list = rawPlugins(for: game) else { return nil }
        for index in list.indices {
            if let name = list[index]["name"] as? String, let status = map[name] {
                list[index]["status"] = status
            }
        }
        guard let json = try? JSONSerialization.data(withJSONObject: list, options: [.prettyPrinted]) else { return nil }
        var out = Data("// Generated by NexPlay from js/plugins.js with plugin overrides.\nvar $plugins =\n".utf8)
        out.append(json)
        out.append(Data(";\n".utf8))
        return out
    }

    /// The scheme handler's override for this game's js/plugins.js.
    static func fileOverride(for game: Game) -> ((String) -> Data?)? {
        guard game.engine.isRPGMaker else { return nil }
        let folder = (game.entry as NSString).deletingLastPathComponent
        let target = (folder.isEmpty ? "js/plugins.js" : folder + "/js/plugins.js").lowercased()
        return { path in
            guard path == target else { return nil }
            return PluginManager.generatedPluginsJS(for: game)
        }
    }
}

struct PluginListView: View {
    @Environment(\.dismiss) private var dismiss
    let game: Game
    var onChange: () -> Void = {}

    @State private var plugins: [PluginEntry] = []
    @State private var overrides: [String: Bool] = [:]

    var body: some View {
        NavigationStack {
            List {
                Section {
                    ForEach(plugins) { plugin in
                        Toggle(isOn: Binding(
                            get: { overrides[plugin.name] ?? plugin.originalStatus },
                            set: { value in
                                if value == plugin.originalStatus {
                                    overrides[plugin.name] = nil
                                } else {
                                    overrides[plugin.name] = value
                                }
                                PluginManager.setOverrides(overrides, for: game)
                                onChange()
                            }
                        )) {
                            VStack(alignment: .leading, spacing: 2) {
                                HStack {
                                    Text(plugin.name).font(.body)
                                    if overrides[plugin.name] != nil {
                                        Text("Changed").font(.caption2).foregroundStyle(.orange)
                                    }
                                }
                                if !plugin.description.isEmpty {
                                    Text(plugin.description).font(.caption).foregroundStyle(.secondary).lineLimit(2)
                                }
                            }
                        }
                    }
                } footer: {
                    Text(plugins.isEmpty
                         ? "No js/plugins.js found."
                         : "Turning plugins off can break a game. Changes apply when the game restarts. The game's own file is not changed.")
                }
                if !overrides.isEmpty {
                    Section {
                        Button("Reset All Plugins", role: .destructive) {
                            overrides = [:]
                            PluginManager.setOverrides([:], for: game)
                            onChange()
                        }
                    }
                }
            }
            .navigationTitle("Plugins")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .navigationBarTrailing) { Button("Done") { dismiss() } }
            }
            .onAppear {
                plugins = PluginManager.plugins(for: game)
                overrides = PluginManager.overrides(for: game)
            }
        }
    }
}

final class PluginsFeature: PlayerFeature {
    private var changed = false

    override func menuItems(for game: Game) -> [UIMenuElement] {
        guard game.engine.isRPGMaker else { return [] }
        return [UIAction(title: "Plugins…", image: UIImage(systemName: "puzzlepiece.extension")) { [weak self] _ in
            self?.showPlugins()
        }]
    }

    private func showPlugins() {
        let game = context.game()
        let view = PluginListView(game: game, onChange: { [weak self] in self?.changed = true })
        let host = UIHostingController(rootView: view)
        context.present(host)
    }

    override func didFinishLoad() {
        changed = false
    }
}

// MARK: - Cheats

final class CheatsFeature: PlayerFeature {
    private var god = false
    private var through = false
    private var noEncounters = false

    static let script = #"""
    (function () {
        function ready() { return typeof $gameParty !== 'undefined' && $gameParty && typeof $gamePlayer !== 'undefined' && $gamePlayer; }
        window.__nexCheat = function (name, a, b) {
            try {
                if (!ready()) return 'Start or load a game first.';
                switch (name) {
                case 'gold': $gameParty.gainGold(Number(a) || 0); break;
                case 'heal': $gameParty.members().forEach(function (m) { m.recoverAll(); }); break;
                case 'item': case 'weapon': case 'armor':
                    var table = name === 'item' ? $dataItems : name === 'weapon' ? $dataWeapons : $dataArmors;
                    var thing = table && table[Number(a)];
                    if (!thing) return 'No ' + name + ' with id ' + a + '.';
                    $gameParty.gainItem(thing, Number(b) || 1);
                    break;
                case 'through': window.__nexThrough = !!a; $gamePlayer.setThrough(!!a); break;
                case 'encounters': window.__nexNoEncounters = !!a; break;
                case 'god': window.__nexGod = !!a; break;
                case 'switch': $gameSwitches.setValue(Number(a), !!b); break;
                case 'variable': $gameVariables.setValue(Number(a), Number(b) || 0); break;
                default: return 'Unknown cheat.';
                }
                return 'ok';
            } catch (e) { return String(e); }
        };
        (function hook() {
            if (typeof Game_Player === 'undefined' || typeof Game_Battler === 'undefined') { setTimeout(hook, 500); return; }
            if (Game_Player.prototype.__nexHooked) return;
            Game_Player.prototype.__nexHooked = true;
            var canEncounter = Game_Player.prototype.canEncounter;
            Game_Player.prototype.canEncounter = function () {
                return window.__nexNoEncounters ? false : canEncounter.apply(this, arguments);
            };
            var gainHp = Game_Battler.prototype.gainHp;
            Game_Battler.prototype.gainHp = function (value) {
                if (window.__nexGod && this.isActor && this.isActor() && value < 0) value = 0;
                return gainHp.call(this, value);
            };
            var isThrough = Game_Player.prototype.isThrough;
            Game_Player.prototype.isThrough = function () {
                return window.__nexThrough ? true : isThrough.apply(this, arguments);
            };
        })();
    })();
    """#

    override func userScripts(for game: Game) -> [WKUserScript] {
        guard game.engine.isRPGMaker else { return [] }
        return [WKUserScript(source: CheatsFeature.script, injectionTime: .atDocumentEnd, forMainFrameOnly: true)]
    }

    override func didFinishLoad() {
        god = false
        through = false
        noEncounters = false
    }

    override func menuItems(for game: Game) -> [UIMenuElement] {
        guard game.engine.isRPGMaker else { return [] }
        let toggles: [UIMenuElement] = [
            UIAction(title: "God Mode", state: god ? .on : .off) { [weak self] _ in
                guard let self else { return }
                self.god.toggle()
                self.run("god", self.god ? "1" : "0")
            },
            UIAction(title: "Walk Through Walls", state: through ? .on : .off) { [weak self] _ in
                guard let self else { return }
                self.through.toggle()
                self.run("through", self.through ? "1" : "0")
            },
            UIAction(title: "No Random Encounters", state: noEncounters ? .on : .off) { [weak self] _ in
                guard let self else { return }
                self.noEncounters.toggle()
                self.run("encounters", self.noEncounters ? "1" : "0")
            },
        ]
        let actions: [UIMenuElement] = [
            UIAction(title: "Add Gold…") { [weak self] _ in self?.ask("Add gold", fields: ["Amount"]) { self?.run("gold", $0[0]) } },
            UIAction(title: "Heal Party") { [weak self] _ in self?.run("heal", "0") },
            UIAction(title: "Give Item…") { [weak self] _ in self?.ask("Give item", fields: ["Item ID", "Amount"]) { self?.run("item", $0[0], $0[1]) } },
            UIAction(title: "Give Weapon…") { [weak self] _ in self?.ask("Give weapon", fields: ["Weapon ID", "Amount"]) { self?.run("weapon", $0[0], $0[1]) } },
            UIAction(title: "Give Armor…") { [weak self] _ in self?.ask("Give armor", fields: ["Armor ID", "Amount"]) { self?.run("armor", $0[0], $0[1]) } },
            UIAction(title: "Set Switch…") { [weak self] _ in self?.ask("Set switch", fields: ["Switch ID", "1 = on, 0 = off"]) { self?.run("switch", $0[0], $0[1]) } },
            UIAction(title: "Set Variable…") { [weak self] _ in self?.ask("Set variable", fields: ["Variable ID", "Value"]) { self?.run("variable", $0[0], $0[1]) } },
        ]
        return [UIMenu(title: "Cheats", image: UIImage(systemName: "wand.and.stars"),
                       children: [UIMenu(options: .displayInline, children: toggles)] + actions)]
    }

    /// Calls window.__nexCheat with numbers only, so nothing typed can run as script.
    private func run(_ name: String, _ a: String, _ b: String = "0") {
        let first = Double(a.trimmingCharacters(in: .whitespaces)) ?? 0
        let second = Double(b.trimmingCharacters(in: .whitespaces)) ?? 0
        let numbers = "\(first), \(second)"
        let script = "window.__nexCheat ? window.__nexCheat('\(name)', \(numbers)) : 'Cheats are not ready.'"
        context.webView?.evaluateJavaScript(script) { [weak self] result, _ in
            if let text = result as? String, text != "ok" {
                self?.show(text)
            } else {
                self?.context.gameLog.add("cheat: \(name)")
            }
        }
    }

    private func ask(_ title: String, fields: [String], done: @escaping ([String]) -> Void) {
        let alert = UIAlertController(title: title, message: nil, preferredStyle: .alert)
        for field in fields {
            alert.addTextField { text in
                text.placeholder = field
                text.keyboardType = .numbersAndPunctuation
            }
        }
        alert.addAction(UIAlertAction(title: "Cancel", style: .cancel))
        alert.addAction(UIAlertAction(title: "OK", style: .default) { [weak alert] _ in
            let values = (alert?.textFields ?? []).map { $0.text ?? "" }
            done(values + ["", ""])
        })
        context.present(alert)
    }

    private func show(_ message: String) {
        let alert = UIAlertController(title: "Cheats", message: message, preferredStyle: .alert)
        alert.addAction(UIAlertAction(title: "OK", style: .default))
        context.present(alert)
    }
}
